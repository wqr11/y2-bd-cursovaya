-- =====================================================================
-- БД «Адвокатская контора». СУБД: PostgreSQL 16
-- ЭТАП 0. НЕНОРМАЛИЗОВАННАЯ схема (функциональная копия итоговой БД)
--
-- Намеренные недостатки схемы (устраняются миграциями 03–06):
--   * ФИО и паспорт хранятся одной строкой (нарушение 1НФ);
--   * сведения о статье (название, пределы санкции) повторяются в каждой
--     строке связи «дело – статья» (частичная зависимость, нарушение 2НФ);
--   * сведения о суде и виде исхода дела записываются текстом прямо в
--     каждое дело (транзитивные зависимости, нарушение 3НФ).
--
-- Перед запуском:  CREATE DATABASE advocate_unf ENCODING 'UTF8';
-- =====================================================================

DROP TABLE IF EXISTS settlements    CASCADE;
DROP TABLE IF EXISTS cases_articles CASCADE;
DROP TABLE IF EXISTS cases          CASCADE;
DROP TABLE IF EXISTS clients        CASCADE;
DROP TABLE IF EXISTS attorneys      CASCADE;

-- Адвокаты: full_name = «Фамилия Имя Отчество» (составной атрибут)
CREATE TABLE attorneys (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name      VARCHAR(300) NOT NULL,
    license_number VARCHAR(20)  NOT NULL UNIQUE,
    admission_date DATE         NOT NULL,
    phone          VARCHAR(12)  NOT NULL UNIQUE,
    email          VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT chk_attorneys_license   CHECK (license_number ~ '^[0-9]{2}/[0-9]{1,5}$'),
    CONSTRAINT chk_attorneys_admission CHECK (admission_date >= DATE '1990-01-01'),
    CONSTRAINT chk_attorneys_phone     CHECK (phone ~ '^\+7[0-9]{10}$'),
    CONSTRAINT chk_attorneys_email     CHECK (email LIKE '%_@_%._%')
);

-- Клиенты: full_name = «Фамилия Имя Отчество», passport = «СССС НННННН»
CREATE TABLE clients (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(300) NOT NULL,
    birth_date    DATE         NOT NULL,
    passport      VARCHAR(11)  NOT NULL UNIQUE,
    phone         VARCHAR(12)  NOT NULL,
    address       VARCHAR(255) NOT NULL,
    registered_at DATE         NOT NULL DEFAULT CURRENT_DATE,
    attorney_id   INTEGER      NOT NULL,
    CONSTRAINT chk_clients_passport CHECK (passport ~ '^[0-9]{4} [0-9]{6}$'),
    CONSTRAINT chk_clients_phone    CHECK (phone ~ '^\+7[0-9]{10}$'),
    CONSTRAINT chk_clients_birth    CHECK (birth_date >= DATE '1900-01-01'),
    CONSTRAINT chk_clients_age      CHECK (registered_at >= birth_date + INTERVAL '14 years'),
    CONSTRAINT fk_clients_attorney  FOREIGN KEY (attorney_id)
        REFERENCES attorneys(id) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Дела: суд и вид исхода записаны текстом в каждой строке (повторяются)
CREATE TABLE cases (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number            VARCHAR(30)   NOT NULL UNIQUE,
    client_id              INTEGER       NOT NULL,
    taken_date             TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    settled_date           TIMESTAMP,
    agreed_fee             NUMERIC(12,2) NOT NULL,
    description            TEXT,
    court_name             VARCHAR(150)  NOT NULL,
    court_city             VARCHAR(100)  NOT NULL,
    court_address          VARCHAR(255)  NOT NULL,
    court_phone            VARCHAR(12),
    verdict_name           VARCHAR(100),
    verdict_legal_basis    VARCHAR(50),
    verdict_is_real_prison BOOLEAN,
    sentence_days          INTEGER,
    fine_amount            NUMERIC(12,2),
    CONSTRAINT chk_cases_number   CHECK (case_number ~ '^[0-9]+-[0-9]+/[0-9]{4}$'),
    CONSTRAINT chk_cases_fee      CHECK (agreed_fee >= 0),
    CONSTRAINT chk_cases_sentence CHECK (sentence_days >= 0),
    CONSTRAINT chk_cases_fine     CHECK (fine_amount >= 0),
    CONSTRAINT chk_cases_dates    CHECK (settled_date IS NULL OR settled_date >= taken_date),
    CONSTRAINT chk_cases_closure  CHECK (
        (settled_date IS NULL AND verdict_name IS NULL AND verdict_legal_basis IS NULL
            AND verdict_is_real_prison IS NULL AND sentence_days IS NULL AND fine_amount IS NULL)
        OR
        (settled_date IS NOT NULL AND verdict_name IS NOT NULL AND verdict_legal_basis IS NOT NULL
            AND verdict_is_real_prison IS NOT NULL AND sentence_days IS NOT NULL AND fine_amount IS NOT NULL)
    ),
    CONSTRAINT fk_cases_client FOREIGN KEY (client_id)
        REFERENCES clients(id) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Статьи дела: сведения о статье повторяются для каждого дела
CREATE TABLE cases_articles (
    case_id           INTEGER      NOT NULL,
    article_code      VARCHAR(20)  NOT NULL,
    article_title     VARCHAR(200) NOT NULL,
    min_sentence_days INTEGER      NOT NULL DEFAULT 0,
    max_sentence_days INTEGER      NOT NULL,
    PRIMARY KEY (case_id, article_code),
    CONSTRAINT chk_ca_range CHECK (min_sentence_days >= 0 AND max_sentence_days >= min_sentence_days),
    FOREIGN KEY (case_id) REFERENCES cases(id) ON DELETE RESTRICT ON UPDATE CASCADE
);

-- Расчёты с клиентом: способ оплаты хранится текстом
CREATE TABLE settlements (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id        INTEGER       NOT NULL,
    settled_date   TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount         NUMERIC(12,2) NOT NULL,
    payment_method VARCHAR(20)   NOT NULL DEFAULT 'Банковский перевод',
    CONSTRAINT chk_settlements_amount CHECK (amount > 0),
    CONSTRAINT chk_settlements_method CHECK (payment_method IN ('Наличные', 'Банковский перевод', 'Банковская карта')),
    CONSTRAINT fk_settlements_case FOREIGN KEY (case_id)
        REFERENCES cases(id) ON DELETE RESTRICT ON UPDATE CASCADE
);