-- =====================================================================
-- БД «Адвокатская контора» (тема 9). СУБД: PostgreSQL 16
-- Создание структуры (3НФ) и заполнение тестовыми данными.
-- Все персональные данные вымышлены, совпадения случайны.
--
-- Перед запуском создайте базу данных:
--   CREATE DATABASE advocate_db ENCODING 'UTF8';
-- и подключитесь к ней (\c advocate_db).
-- =====================================================================

-- ---------------------------------------------------------------------
-- 0. Очистка (скрипт можно запускать повторно)
-- ---------------------------------------------------------------------
DROP TABLE IF EXISTS settlements        CASCADE;
DROP TABLE IF EXISTS cases_to_articles  CASCADE;
DROP TABLE IF EXISTS cases              CASCADE;
DROP TABLE IF EXISTS clients            CASCADE;
DROP TABLE IF EXISTS attorneys          CASCADE;
DROP TABLE IF EXISTS articles           CASCADE;
DROP TABLE IF EXISTS verdict_types      CASCADE;
DROP TABLE IF EXISTS courts             CASCADE;
DROP TYPE  IF EXISTS payment_method;

-- ---------------------------------------------------------------------    
-- 1. Пользовательский тип: способ оплаты
-- ---------------------------------------------------------------------
CREATE TYPE payment_method AS ENUM ('Наличные', 'Банковский перевод', 'Банковская карта');

-- ---------------------------------------------------------------------
-- 2. Справочники
-- ---------------------------------------------------------------------

-- Суды
CREATE TABLE courts (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(150) NOT NULL UNIQUE,
    city    VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    phone   VARCHAR(12),
    CONSTRAINT chk_courts_phone CHECK (phone IS NULL OR phone ~ '^\+7[0-9]{10}$')
);

-- Виды исхода дела (приговор, прекращение дела и т.п.)
CREATE TABLE verdict_types (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(100) NOT NULL UNIQUE,
    legal_basis    VARCHAR(50)  NOT NULL,
    is_real_prison BOOLEAN      NOT NULL DEFAULT FALSE
);

-- Статьи Уголовного кодекса РФ (с частью статьи)
CREATE TABLE articles (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code              VARCHAR(20)  NOT NULL UNIQUE,
    title             VARCHAR(200) NOT NULL,
    min_sentence_days INTEGER      NOT NULL DEFAULT 0,
    max_sentence_days INTEGER      NOT NULL,
    CONSTRAINT chk_articles_min   CHECK (min_sentence_days >= 0),
    CONSTRAINT chk_articles_range CHECK (max_sentence_days >= min_sentence_days)
);

-- ---------------------------------------------------------------------
-- 3. Основные таблицы
-- ---------------------------------------------------------------------

-- Адвокаты
CREATE TABLE attorneys (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lastname       VARCHAR(100) NOT NULL,
    firstname      VARCHAR(100) NOT NULL,
    middlename     VARCHAR(100),
    license_number VARCHAR(20)  NOT NULL UNIQUE,
    admission_date DATE         NOT NULL,
    phone          VARCHAR(12)  NOT NULL UNIQUE,
    email          VARCHAR(100) NOT NULL UNIQUE,
    CONSTRAINT chk_attorneys_license   CHECK (license_number ~ '^[0-9]{2}/[0-9]{1,5}$'),
    CONSTRAINT chk_attorneys_admission CHECK (admission_date >= DATE '1990-01-01'),
    CONSTRAINT chk_attorneys_phone     CHECK (phone ~ '^\+7[0-9]{10}$'),
    CONSTRAINT chk_attorneys_email     CHECK (email LIKE '%_@_%._%')
);

-- Клиенты (за каждым клиентом закреплён один адвокат)
CREATE TABLE clients (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lastname        VARCHAR(100) NOT NULL,
    firstname       VARCHAR(100) NOT NULL,
    middlename      VARCHAR(100),
    birth_date      DATE         NOT NULL,
    passport_series CHAR(4)      NOT NULL,
    passport_number CHAR(6)      NOT NULL,
    phone           VARCHAR(12)  NOT NULL,
    address         VARCHAR(255) NOT NULL,
    registered_at   DATE         NOT NULL DEFAULT CURRENT_DATE,
    attorney_id     INTEGER      NOT NULL,
    CONSTRAINT uq_clients_passport UNIQUE (passport_series, passport_number),
    CONSTRAINT chk_clients_series   CHECK (passport_series ~ '^[0-9]{4}$'),
    CONSTRAINT chk_clients_number   CHECK (passport_number ~ '^[0-9]{6}$'),
    CONSTRAINT chk_clients_phone    CHECK (phone ~ '^\+7[0-9]{10}$'),
    CONSTRAINT chk_clients_birth    CHECK (birth_date >= DATE '1900-01-01'),
    CONSTRAINT chk_clients_age      CHECK (registered_at >= birth_date + INTERVAL '14 years'),
    CONSTRAINT fk_clients_attorney  FOREIGN KEY (attorney_id)
        REFERENCES attorneys(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Дела (завершённое дело = архивное: заполнены дата завершения и исход)
CREATE TABLE cases (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number     VARCHAR(30)   NOT NULL UNIQUE,
    client_id       INTEGER       NOT NULL,
    court_id        INTEGER       NOT NULL,
    verdict_type_id INTEGER,
    taken_date      TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    settled_date    TIMESTAMP,
    agreed_fee      NUMERIC(12,2) NOT NULL,
    sentence_days   INTEGER,
    fine_amount     NUMERIC(12,2),
    description     TEXT,
    CONSTRAINT chk_cases_number   CHECK (case_number ~ '^[0-9]+-[0-9]+/[0-9]{4}$'),
    CONSTRAINT chk_cases_fee      CHECK (agreed_fee >= 0),
    CONSTRAINT chk_cases_sentence CHECK (sentence_days >= 0),
    CONSTRAINT chk_cases_fine     CHECK (fine_amount >= 0),
    CONSTRAINT chk_cases_dates    CHECK (settled_date IS NULL OR settled_date >= taken_date),
    CONSTRAINT chk_cases_closure  CHECK (
        (settled_date IS NULL AND verdict_type_id IS NULL
            AND sentence_days IS NULL AND fine_amount IS NULL)
        OR
        (settled_date IS NOT NULL AND verdict_type_id IS NOT NULL
            AND sentence_days IS NOT NULL AND fine_amount IS NOT NULL)
    ),
    CONSTRAINT fk_cases_client FOREIGN KEY (client_id)
        REFERENCES clients(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_cases_court FOREIGN KEY (court_id)
        REFERENCES courts(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_cases_verdict FOREIGN KEY (verdict_type_id)
        REFERENCES verdict_types(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Связь «дело — статьи» (многие ко многим)
CREATE TABLE cases_to_articles (
    case_id    INTEGER NOT NULL,
    article_id INTEGER NOT NULL,
    CONSTRAINT pk_cases_to_articles PRIMARY KEY (case_id, article_id),
    CONSTRAINT fk_cta_case FOREIGN KEY (case_id)
        REFERENCES cases(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,
    CONSTRAINT fk_cta_article FOREIGN KEY (article_id)
        REFERENCES articles(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

-- Расчёты с клиентом: у дела может быть несколько платежей по гонорару
CREATE TABLE settlements (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id        INTEGER        NOT NULL,
    settled_date   TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    amount         NUMERIC(12,2)  NOT NULL,
    payment_method payment_method NOT NULL DEFAULT 'Банковский перевод',
    CONSTRAINT chk_settlements_amount CHECK (amount > 0),
    CONSTRAINT fk_settlements_case FOREIGN KEY (case_id)
        REFERENCES cases(id)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);
